const assert = require('node:assert/strict');
const M = require('../src/app/sync/model');
const P = require('../src/app/sync/presentation');
const snapshot = {id:'review',tripName:'교토',itineraryItems:[{id:'item',date:'2026-09-26',time:'10:00',endTime:'11:00',place:'교토역'}]};
const baseline = M.encode(snapshot), remote = M.clone(baseline);
remote[M.key('itinerary','item')].fields['g:schedule'].time='10:30';
const patch = {kind:'itinerary',id:'item',action:'patch',before:{'g:schedule':{date:'2026-09-26',time:'09:00'}},fields:{'g:schedule':{date:'2026-09-26',time:'10:00',endTime:'11:00'}}};
const conflict={id:'review-conflict',source:'server',snapshot,patches:[patch]};
const record={snapshot,base:remote,conflicts:[conflict]};
let preview=P.comparison(record,conflict,patch);
assert.equal(preview.local.headline,'10:00');assert.equal(preview.shared.headline,'10:30');
assert.equal(preview.local.caption,'교토역');assert.equal(preview.title,'시간 변경');
assert.equal(preview.shared.rows.find(r=>r.label==='종료 시간').value,'11:00');
assert.equal(P.date('2026-09-26'),'9월 26일 (토)');
assert.equal(P.badge({tone:'warning'},record).label,'확인 1건');
assert.equal(P.badge({tone:'error'},record).label,'저장 확인','A storage failure takes precedence over a conflict badge');
assert.equal(P.comparison(record,conflict,{...patch,fields:{'g:schedule':null}}).local.headline,'시간 미정');
const deleted=M.clone(remote);deleted[M.key('itinerary','item')].deleted=true;
assert.equal(P.comparison({...record,base:deleted},conflict,patch).shared.headline,'삭제된 항목');
const absent=M.clone(remote);delete absent[M.key('itinerary','item')];
assert.equal(P.comparison({...record,base:absent},conflict,patch).shared.headline,'삭제된 항목');
assert.equal(P.comparison(record,conflict,{...patch,action:'delete'}).local.headline,'일정 삭제');
const tabSnapshot=M.clone(snapshot);tabSnapshot.itineraryItems[0].time='13:00';
preview=P.comparison({...record,snapshot:tabSnapshot},{...conflict,source:'tab'},patch);
assert.equal(preview.sharedLabel,'다른 탭의 내용');assert.equal(preview.shared.headline,'13:00');
const voucher={...patch,fields:{'g:voucher':{voucherFile:'data:image/png;base64,PRIVATE_FILE_BYTES',voucherFileName:'예약.png'}}};
preview=P.comparison(record,conflict,voucher);
assert(!JSON.stringify(preview).includes('PRIVATE_FILE_BYTES'));assert(JSON.stringify(preview).includes('첨부파일 있음'));
assert.equal(P.count({...record,conflicts:[{patches:[patch,voucher]},{patches:[patch]}]}),3);
const orderedSnapshot={id:'order-review',itineraryItems:['A','B','C'].map((place,i)=>({id:place,place,date:'2026-09-26',itineraryOrder:{date:'2026-09-26',rank:(i+1)*1024}}))};
const orderedBase=M.encode(orderedSnapshot);
orderedBase['itinerary:C'].fields['p:itineraryOrder'].rank=512;
const orderPatch={kind:'itinerary',id:'C',action:'patch',fields:{'p:itineraryOrder':{date:'2026-09-26',rank:1536}}};
const orderPreview=P.comparison({snapshot:orderedSnapshot,base:orderedBase},{source:'server',snapshot:orderedSnapshot,patches:[orderPatch]},orderPatch);
assert.equal(orderPreview.title,'일정 순서 변경');
assert.equal(orderPreview.local.rows[0].value,'A 다음 · B 이전');
assert.equal(orderPreview.shared.rows[0].value,'맨 처음 · A 이전');
console.log('PASS conflict presentation: latest shared value vs local candidate, tab edits, deleted fields/entities, linked-change counts, attachment redaction and storage-error priority.');
