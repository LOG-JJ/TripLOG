const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { PGlite } = require('@electric-sql/pglite');
const M = require('../src/app/sync/model');
const root = path.resolve(__dirname, '..');
const actors = ['00000000-0000-4000-8000-000000000001','00000000-0000-4000-8000-000000000002','00000000-0000-4000-8000-000000000003','00000000-0000-4000-8000-000000000004'];
async function createDatabase() {
  const db = new PGlite();
  await db.exec(`create role anon; create role authenticated; create role service_role bypassrls;
    create schema auth; create table auth.users(id uuid primary key);
    create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
    create schema realtime; create table realtime.messages(topic text,extension text);
    alter table realtime.messages enable row level security;
    create function realtime.topic() returns text language sql stable as $$ select current_setting('request.channel',true) $$;
    grant usage on schema auth,realtime to authenticated,service_role;
    grant select on realtime.messages to authenticated;
  `);
  await db.exec(fs.readFileSync(path.join(root,'supabase/triplog-collaboration.sql'),'utf8').replace('create extension if not exists pgcrypto;', ''));
  await db.exec(fs.readFileSync(path.join(root,'supabase/migrations/20260919143539_realtime_collaboration_v2.sql'),'utf8'));
  await db.exec(fs.readFileSync(path.join(root,'supabase/migrations/20260919144121_fix_sync_service_auth_permissions.sql'),'utf8'));
  await db.exec(fs.readFileSync(path.join(root,'supabase/migrations/20260921134457_safe_history_restore.sql'),'utf8'));
  await db.exec(fs.readFileSync(path.join(root,'supabase/migrations/20261026065147_trip_removal_lifecycle.sql'),'utf8'));
  await db.exec(fs.readFileSync(path.join(root,'supabase/migrations/20261031153950_companion_reservation_money_privacy.sql'),'utf8'));
  await db.exec(fs.readFileSync(path.join(root,'supabase/migrations/20261103090000_member_expense_splits.sql'),'utf8'));
  // Hosted Supabase service_role cannot SELECT auth.users; the verified API and
  // foreign keys establish identity without extending access to auth internals.
  await db.exec('grant all on all tables in schema public to service_role;');
  for (const id of actors) await db.query('insert into auth.users values($1)',[id]);
  return db;
}
async function regression() {
  const db = await createDatabase();
  const snapshot = { id:'fixture-kyoto',tripName:'협업 회귀 여행',startDate:'2026-09-25',endDate:'2026-09-28',entries:[],companions:[],packingList:[],itineraryItems:[{id:'day2',date:'2026-09-26',time:'10:00',endTime:'11:00',place:'교토역'}],collaboration:{privacy:{shareItinerary:true,shareExpenses:true,showMemberEmail:false,allowInviteRequests:true}} };
  const call = async (name, args) => (await db.query(`select public.${name}(${args.map((_,i)=>'$'+(i+1)).join(',')}) as result`, args.map(v=>v&&typeof v==='object'?JSON.stringify(v):v))).rows[0].result;
  await db.exec('set role service_role');
  await assert.rejects(db.query('select id from auth.users'), /permission denied/);
  const trip = await call('triplog_create_sync',[actors[0],snapshot.id,snapshot,Object.values(M.encode(snapshot))]);
  await db.exec('reset role');
  await db.query("insert into public.triplog_trip_members(trip_id,user_id,role,status) values($1,$2,'editor','accepted'),($1,$3,'viewer','accepted')",[trip,actors[1],actors[2]]);
  const read = actor=>call('triplog_read_sync',[actor,trip,null]);
  const baseline=M.fromRows((await read(actors[0])).entities);
  const make = (before, after)=>({ protocolVersion:2,operationId:M.uuid(),patches:M.diff(before,after) });
  const patch = (entities, id, field, value)=>{const copy=M.clone(entities);copy[M.key('itinerary',id)].fields[field]=value;return copy;};
  const time = make(baseline,patch(baseline,'day2','g:schedule',{date:'2026-09-26',time:'12:00',endTime:'13:00'}));
  const place = make(baseline,patch(baseline,'day2','g:place',{place:'清水寺'}));
  assert.equal((await call('triplog_apply_sync',[actors[0],trip,time])).status,'applied');
  assert.equal((await call('triplog_apply_sync',[actors[1],trip,place])).status,'applied');
  let current=await read(actors[0]);
  let item=M.fromRows(current.entities)[M.key('itinerary','day2')];
  assert.equal(item.fields['g:schedule'].time,'12:00');assert.equal(item.fields['g:place'].place,'清水寺');
  const conflicting=make(baseline,patch(baseline,'day2','g:schedule',{date:'2026-09-26',time:'14:00',endTime:'15:00'}));
  assert.equal((await call('triplog_apply_sync',[actors[1],trip,conflicting])).status,'conflict');
  assert.equal((await call('triplog_apply_sync',[actors[0],trip,time])).status,'applied');
  assert.equal((await read(actors[0])).head,2,'Lost response retry must not increment cursor');
  await assert.rejects(call('triplog_apply_sync',[actors[0],trip,{...time,patches:place.patches}]),/REUSED/);
  await assert.rejects(call('triplog_apply_sync',[actors[2],trip,{...place,operationId:M.uuid()}]),/FORBIDDEN/);
  await assert.rejects(read(actors[3]),/FORBIDDEN/);
  const delta=await call('triplog_read_sync',[actors[0],trip,0]);
  assert.equal(delta.cursor,2);assert.equal(delta.entities.length,2);
  const beforeDelete=M.fromRows((await read(actors[0])).entities), afterDelete=M.clone(beforeDelete);delete afterDelete[M.key('itinerary','day2')];
  assert.equal((await call('triplog_apply_sync',[actors[0],trip,make(beforeDelete,afterDelete)])).status,'applied');
  const stale=make(beforeDelete,patch(beforeDelete,'day2','g:place',{place:'삭제 후 편집'}));
  assert.equal((await call('triplog_apply_sync',[actors[1],trip,stale])).status,'conflict');
  const another=make({}, { [M.key('expense','new-expense')]:{kind:'expense',id:'new-expense',fields:{'g:money':{amount:30000},'p:description':'점심'}} });
  assert.equal((await call('triplog_apply_sync',[actors[0],trip,another])).status,'applied');
  const invalid={protocolVersion:2,operationId:M.uuid(),patches:[{kind:'expense',id:'invalid',action:'create',fields:{'g:money':{amount:-100}},before:null}]};
  await assert.rejects(call('triplog_apply_sync',[actors[0],trip,invalid]),/INVALID_AMOUNT/);
  await call('triplog_sync_control',[actors[0],trip,'privacy',{shareExpenses:false,shareItinerary:true,showMemberEmail:false,allowInviteRequests:true}]);
  assert.ok(!(await read(actors[1])).entities.some(e=>e.kind==='expense'));
  const editorDelta=await call('triplog_read_sync',[actors[1],trip,0]);
  assert.ok(!editorDelta.entities.some(e=>e.kind==='expense'));
  assert.equal(editorDelta.cursor,(await read(actors[0])).head,'Redacted events still advance the scanned cursor');
  await db.exec(`set role authenticated; set request.jwt.claim.sub='${actors[0]}';`);
  await assert.rejects(db.query('update public.triplog_trips set travel_state=$1 where id=$2',[JSON.stringify({itineraryItems:[]}),trip]),/permission denied/);
  await assert.rejects(call('triplog_apply_sync',[actors[0],trip,time]),/permission denied/);
  await db.exec('reset role;');
  assert.equal((await db.query('select count(*)::int as count from public.triplog_change_log')).rows[0].count,4);
  assert.equal((await db.query('select count(*)::int as count from public.triplog_recovery_snapshots')).rows[0].count,1);
  await db.close();
  console.log('PASS database: independent fields, same-field conflicts, idempotent retries, receipts, deletion/edit races, amount validation, privacy/redacted cursors, membership roles, legacy-write rejection and recovery history.');
}
if (require.main===module) regression().catch(error=>{console.error(error);process.exitCode=1;});
module.exports={createDatabase,actors};
