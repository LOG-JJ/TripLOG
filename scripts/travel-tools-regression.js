'use strict';
const assert=require('node:assert/strict');
const T=require('../src/app/features/travel-companion/tools-model');
const sun=require('suncalc');
assert.deepEqual(T.convertTime('2026-11-03','09:00','Asia/Seoul','America/New_York'),{date:'2026-11-02',time:'19:00',dayDiff:-1,delta:-14});
assert.equal(T.convertTime('2026-07-03','09:00','Asia/Seoul','America/New_York').delta,-13);
assert.throws(()=>T.convertTime('2026-03-08','02:30','America/New_York','Asia/Seoul'),/존재하지 않는/);
assert.throws(()=>T.convertTime('2026-11-01','01:30','America/New_York','Asia/Seoul'),/두 번/);
assert.equal(T.convertTime('2026-11-03','09:00','Asia/Seoul','Asia/Kolkata').time,'05:30');
assert.equal(T.convertTime('2026-11-03','23:30','Pacific/Honolulu','Pacific/Auckland').dayDiff,1);
const tokyo=T.destination({city:'Tokyo',countryCode:'JP'}),solar=T.solar(tokyo,'2026-11-03',sun,new Date('2026-11-03T05:30Z'));
assert.match(solar.sunrise,/^06:0\d$/);assert.match(solar.sunset,/^16:4\d$/);assert(solar.minutes>630&&solar.minutes<650);assert.equal(solar.today,true);
assert.equal(T.solar(T.cities.find(city=>city.name==='트롬쇠'),'2026-06-21',sun).polar,'백야');
assert.equal(T.solar(T.cities.find(city=>city.name==='트롬쇠'),'2026-12-21',sun).polar,'극야');
assert.equal(T.destination({city:'unknown',countryCode:'JP'}),null);
assert.equal(T.cityList({city:'리옹',itineraryItems:[{lat:45.764,lon:4.8357}],travelCompanion:{timeZone:'Europe/Paris'}})[0].id,'destination');
assert.equal(T.convertUnit('68','temperature','°F'),20);assert.equal(T.convertUnit('-40','temperature','°C'),-40);
assert.equal(T.convertUnit('10','distance','mi'),16.09344);assert(Math.abs(T.convertUnit('10','weight','lb')-4.5359237)<1e-10);
for(const input of ['','abc','1e100','Infinity','1,2'])assert.equal(T.convertUnit(input,'distance','km'),null);
assert.equal(T.convertUnit('-1','distance','km'),null);assert.equal(T.defaults('GB','distance'),'mi');assert.equal(T.defaults('GB','temperature'),'°C');
assert.equal(T.wifiPayload('Cafe;A:B,\\"','password1','WPA'),'WIFI:T:WPA;S:Cafe\\;A\\:B\\,\\\\\\";P:password1;;');
assert.equal(T.wifiPayload('Guest','','nopass'),'WIFI:T:nopass;S:Guest;;');
assert.throws(()=>T.wifiPayload('가'.repeat(11),'password1','WPA'),/32바이트/);
assert.throws(()=>T.wifiPayload('Guest','short','WPA'),/비밀번호/);
const QR=require('qrcode-generator');QR.stringToBytes=value=>Array.from(new TextEncoder().encode(value));
const qr=QR(0,'M');qr.addData(T.wifiPayload('한글 카페','password1','WPA'),'Byte');qr.make();assert(qr.getModuleCount()>20);assert.match(qr.createSvgTag(),/<svg/);
console.log('PASS tools: date rollover, DST gaps/folds, half-hour offsets, solar/polar dates, destination matching, conversions, Wi-Fi escaping/byte limits and UTF-8 QR.');
