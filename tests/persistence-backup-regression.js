const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const context=vm.createContext({window:{TripLog:{register(){}}},calculateSnapshotTotal:s=>(s.entries||[]).reduce((sum,e)=>sum+e.amount,0)});
vm.runInContext(fs.readFileSync(path.join(__dirname,'../src/app/persistence/archive-db.js'),'utf8'),context);
const trip={id:'a',tripName:'서울',entries:[{id:'e',amount:36000,paymentDate:'2026-09-12',payerKey:'companion:민지',receipt:{fingerprint:'test'}}],collaboration:{privacy:{shareExpenses:false}}};
const second={id:'b',tripName:'부산',entries:[]};
const stamp='2026-09-14T00:00:00Z';
const unpack=p=>context.extractArchiveRecordsFromPayload(p);
const emptySnapshots={exportedAt:stamp,records:[],trips:[trip,second]};
const restored=unpack(emptySnapshots);
assert.equal(restored.length,2);
assert.equal(restored[0].state.entries[0].receipt.fingerprint,'test');
assert.equal(restored[0].state.entries[0].payerKey,'companion:민지');
assert.equal(restored[0].state.collaboration.privacy.shareExpenses,false);
assert.deepEqual(Array.from(unpack(emptySnapshots),r=>r.id),Array.from(restored,r=>r.id));
const old={id:'saved',timestamp:stamp,state:{...trip,entries:[]}};
assert.equal(unpack({records:[old],trips:[trip,second],exportedAt:stamp}).length,3);
assert.equal(unpack({records:[{...old,state:trip}],trips:[trip]}).length,1);
assert.equal(unpack({state:trip}).length,1);
assert.equal(unpack(null).length,0);
assert.equal(unpack({trips:[null,{}]}).length,0);
console.log('PASS: unsnapshotted trips, mixed backups, metadata/privacy, repeat import IDs, deduplication, legacy and malformed payloads.');
